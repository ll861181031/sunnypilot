#!/usr/bin/env python3
"""Train one YOLO model on several labeler batches with route-safe splits.

The batches already carry route-level train.txt / val.txt generated by
tools/yolo_dataset. This script concatenates them, verifies that no route is
on both sides, writes absolute-path lists (Ultralytics resolves txt entries
from CWD), trains, validates, exports ONNX and optionally uploads it.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import yaml


def load_dataset(root: Path) -> tuple[dict, list[str], list[str], set[str], set[str]]:
  manifest = json.loads((root / "dataset.json").read_text(encoding="utf-8"))
  ids = {im["id"]: im for im in manifest["images"]}
  train = [line.strip() for line in (root / "train.txt").read_text(encoding="utf-8").splitlines() if line.strip()]
  val = [line.strip() for line in (root / "val.txt").read_text(encoding="utf-8").splitlines() if line.strip()]
  train_routes = {ids[Path(p).stem]["route"] for p in train if Path(p).stem in ids}
  val_routes = {ids[Path(p).stem]["route"] for p in val if Path(p).stem in ids}
  return manifest, train, val, train_routes, val_routes


def main(argv=None) -> int:
  ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
  ap.add_argument("datasets", nargs="+", help="batch directories")
  ap.add_argument("--model", default="yolo11x.pt")
  ap.add_argument("--epochs", type=int, default=60)
  ap.add_argument("--patience", type=int, default=15)
  ap.add_argument("--imgsz", type=int, default=640)
  ap.add_argument("--batch", type=int, default=4)
  ap.add_argument("--workers", type=int, default=8)
  ap.add_argument("--cache", default="ram", help="ram/disk/False")
  ap.add_argument("--freeze", type=int, default=0, help="freeze first N layers")
  ap.add_argument("--device", default="0")
  ap.add_argument("--fraction", type=float, default=1.0, help="train on a fraction (smoke test)")
  ap.add_argument("--project", required=True, help="runs directory on this host")
  ap.add_argument("--name", default="all17_x")
  ap.add_argument("--work", required=True, help="directory for combined data.yaml / txt lists")
  ap.add_argument("--no-export", dest="export_onnx", action="store_false", default=True)
  ap.add_argument("--upload", action="store_true")
  ap.add_argument("--sync-config", default=None)
  args = ap.parse_args(argv)

  roots = [Path(d).resolve() for d in args.datasets]
  names = None
  train_lines: list[str] = []
  val_lines: list[str] = []
  train_routes: set[str] = set()
  val_routes: set[str] = set()
  for root in roots:
    manifest, tr, va, trr, var = load_dataset(root)
    if names is None:
      names = [c["name"] for c in manifest["classes"]]
    elif [c["name"] for c in manifest["classes"]] != names:
      raise SystemExit(f"class mismatch in {root}")
    train_lines += [str((root / p).resolve()) for p in tr]
    val_lines += [str((root / p).resolve()) for p in va]
    train_routes |= trr
    val_routes |= var
  overlap = train_routes & val_routes
  stats = " ".join([
      f"datasets={len(roots)}", f"train={len(train_lines)}", f"val={len(val_lines)}",
      f"train_routes={len(train_routes)}", f"val_routes={len(val_routes)}",
      f"overlap={sorted(overlap)[:5]}"])
  print(stats)
  if overlap:
    raise SystemExit(f"route leakage between train and val: {len(overlap)} routes")
  work = Path(args.work)
  work.mkdir(parents=True, exist_ok=True)
  train_txt = work / "train_abs.txt"
  val_txt = work / "val_abs.txt"
  train_txt.write_text("\n".join(train_lines) + "\n", encoding="utf-8")
  val_txt.write_text("\n".join(val_lines) + "\n", encoding="utf-8")
  data = {"path": work.as_posix(), "train": train_txt.as_posix(), "val": val_txt.as_posix(),
          "names": dict(enumerate(names))}
  data_yaml = work / "data.yaml"
  data_yaml.write_text(yaml.safe_dump(data, allow_unicode=True, sort_keys=False), encoding="utf-8")
  print(f"data.yaml -> {data_yaml} ({len(names)} classes)")

  from ultralytics import YOLO
  import torch
  print(f"torch {torch.__version__} cuda={torch.cuda.is_available()} device={args.device}")
  model = YOLO(args.model)
  results = model.train(data=str(data_yaml), epochs=args.epochs, patience=args.patience,
                        imgsz=args.imgsz, batch=args.batch, workers=args.workers,
                        device=args.device, fraction=args.fraction, cache=args.cache,
                        freeze=args.freeze,
                        project=args.project, name=args.name, exist_ok=True, seed=0,
                        amp=True, plots=True, verbose=True)
  save_dir = Path(getattr(results, "save_dir", Path(args.project) / args.name))
  best = save_dir / "weights" / "best.pt"
  print(f"save_dir={save_dir} best={best} exists={best.is_file()}")
  if not best.is_file():
    print("ERROR: best.pt not found", file=sys.stderr)
    return 1
  metrics = YOLO(str(best)).val(data=str(data_yaml), imgsz=args.imgsz, batch=args.batch,
                                device=args.device, project=str(save_dir), name="val", exist_ok=True)
  try:
    payload = {"save_dir": str(save_dir), "classes": names,
               "results_dict": getattr(metrics, "results_dict", {}),
               "speed": getattr(metrics, "speed", {}),
               "confusion_matrix": getattr(getattr(metrics, "confusion_matrix", None), "matrix", []).tolist()
               if hasattr(getattr(metrics, "confusion_matrix", None), "matrix") else None}
  except Exception as error:
    payload = {"save_dir": str(save_dir), "classes": names, "metrics_error": repr(error)}
  (save_dir / "metrics.json").write_text(json.dumps(payload, ensure_ascii=False, indent=1), encoding="utf-8")
  print(json.dumps({k: v for k, v in payload.get("results_dict", {}).items()
                    if k in ("metrics/precision(B)", "metrics/recall(B)", "metrics/mAP50(B)", "metrics/mAP50-95(B)")},
                   indent=1))
  if args.export_onnx:
    exported = YOLO(str(best)).export(format="onnx", imgsz=args.imgsz, opset=12)
    print(f"exported onnx: {exported}")
    if args.upload:
      from train_yolo import upload_onnx
      upload_onnx(Path(exported), args.sync_config)
      upload_onnx(best, args.sync_config)
  return 0


if __name__ == "__main__":
  raise SystemExit(main())
